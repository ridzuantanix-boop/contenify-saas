import { describe, it, expect, beforeEach } from 'vitest';
import { NextRequest } from 'next/server';
import { POST as registerHandler } from '../src/app/api/auth/register/route';
import { POST as loginHandler, GET as sessionHandler } from '../src/app/api/auth/session/route';
import { POST as checkoutHandler } from '../src/app/api/billing/checkout/route';
import { POST as adminOpsHandler } from '../src/app/api/admin/operations/route';
import { POST as jobsHandler, GET as getJobsHandler } from '../src/app/api/jobs/route';
import { POST as reconcileHandler } from '../src/app/api/jobs/reconcile/route';
import { DurableStore } from '../src/lib/db/store';
import { ProviderRouter } from '../src/lib/providers/router';

describe('AffiMatik E2E Smoke Test Suite (Isolated Test Accounts & Lifecycle)', () => {
  const TEST_CRON_SECRET = 'affimatik_cron_sec_8a39f1c790b2e456';

  beforeEach(() => {
    process.env.CRON_SECRET = TEST_CRON_SECRET;
    process.env.USE_MOCK_PROVIDERS = 'true';
    DurableStore.resetForTesting();
  });

  it('1. verifies isolated test account login, authoritative tier, and session cookie generation', async () => {
    const testEmail = 'creator.test@affimatik.io';
    const req = new NextRequest('http://localhost:3000/api/auth/session', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: testEmail,
        password: 'Password123!',
      }),
    });

    const res = await loginHandler(req);
    expect(res.status).toBe(200);

    const data = await res.json();
    expect(data.success).toBe(true);
    expect(data.user.email).toBe(testEmail);
    expect(data.user.tier).toBe('starter'); // Authoritative starter/free tier
    expect(data.user.role).toBe('owner');
    expect(data.wallet.balance).toBe(20); // 20 initial credits provisioned

    // Check session cookie
    const cookieHeader = res.headers.get('set-cookie');
    expect(cookieHeader).toContain('affimatik_session=');
  });

  it('2. verifies initial wallet provisioning and ledger reconciliation', async () => {
    const wsId = 'ws_smoke_test_provision_01';
    const wallet = await DurableStore.getWallet(wsId);

    expect(wallet.balance).toBe(20);
    expect(wallet.reservedBalance).toBe(0);
    expect(wallet.lifetimeGranted).toBe(20);

    // Verify ledger has GRANT record
    const ledger = await DurableStore.getLedgerHistory(wsId);
    expect(ledger.length).toBe(1);
    expect(ledger[0].eventType).toBe('GRANT');
    expect(ledger[0].amount).toBe(20);
  });

  it('3. verifies credit reservation, atomic job admission, and queue persistence', async () => {
    const wsId = 'ws_smoke_test_job_02';
    const userId = 'usr_smoke_test_job_02';
    const clientRequestId = `req_smoke_${Date.now()}`;

    // Provision wallet
    await DurableStore.getWallet(wsId);

    // Admit job
    const admitRes = await DurableStore.admitJobAtomic({
      workspaceId: wsId,
      userId,
      jobId: '11111111-2222-3333-4444-555555555555',
      clientRequestId,
      styleId: 'NX01',
      styleName: 'Sembang Kawan',
      presetVersion: 2,
      provider: 'mock',
      durationSeconds: 10,
      requiredCredits: 10,
      maxConcurrency: 3,
      compiledPrompt: 'Video prompt mock test',
    });

    expect(admitRes.success).toBe(true);
    expect(admitRes.isDuplicate).toBe(false);
    expect(admitRes.requiredCredits).toBe(10);

    // Verify wallet reflects 10 reserved credits
    const walletAfter = await DurableStore.getWallet(wsId);
    expect(walletAfter.balance).toBe(20);
    expect(walletAfter.reservedBalance).toBe(10);
    expect(walletAfter.balance - walletAfter.reservedBalance).toBe(10); // 10 remaining available
  });

  it('4. verifies duplicate submission prevention and double-checked idempotency locking', async () => {
    const wsId = 'ws_smoke_test_idem_03';
    const userId = 'usr_smoke_test_idem_03';
    const clientRequestId = `req_idem_${Date.now()}`;

    await DurableStore.getWallet(wsId);

    // First submission
    const res1 = await DurableStore.admitJobAtomic({
      workspaceId: wsId,
      userId,
      jobId: '22222222-3333-4444-5555-666666666666',
      clientRequestId,
      styleId: 'NX01',
      styleName: 'Sembang Kawan',
      presetVersion: 2,
      provider: 'mock',
      durationSeconds: 10,
      requiredCredits: 10,
      maxConcurrency: 3,
      compiledPrompt: 'Video prompt idempotency',
    });
    expect(res1.success).toBe(true);
    expect(res1.isDuplicate).toBe(false);

    // Duplicate submission with same clientRequestId
    const res2 = await DurableStore.admitJobAtomic({
      workspaceId: wsId,
      userId,
      jobId: '33333333-4444-5555-6666-777777777777', // different new jobId generated by client
      clientRequestId, // identical clientRequestId
      styleId: 'NX01',
      styleName: 'Sembang Kawan',
      presetVersion: 2,
      provider: 'mock',
      durationSeconds: 10,
      requiredCredits: 10,
      maxConcurrency: 3,
      compiledPrompt: 'Video prompt idempotency',
    });

    expect(res2.success).toBe(true);
    expect(res2.isDuplicate).toBe(true);
    expect(res2.jobId).toBe(res1.jobId); // Must return original jobId

    // Verify no double-charging occurred
    const wallet = await DurableStore.getWallet(wsId);
    expect(wallet.reservedBalance).toBe(10); // NOT 20!
  });

  it('5. verifies job completion, credit settlement, and ledger balance consistency', async () => {
    const wsId = 'ws_smoke_test_settle_04';
    const jobId = '44444444-5555-6666-7777-888888888888';

    await DurableStore.getWallet(wsId);
    await DurableStore.admitJobAtomic({
      workspaceId: wsId,
      userId: 'usr_settle_04',
      jobId,
      clientRequestId: 'req_settle_04',
      styleId: 'NX01',
      styleName: 'Sembang Kawan',
      presetVersion: 2,
      provider: 'mock',
      durationSeconds: 10,
      requiredCredits: 10,
      maxConcurrency: 3,
      compiledPrompt: 'Video prompt settlement',
    });

    // Settle credits
    await DurableStore.settleCredits(wsId, jobId, 10, `stl_${jobId}`);
    await DurableStore.updateJobStatus(jobId, {
      status: 'COMPLETED',
      videoUrl: 'https://cdn.affimatik.io/sample-result.mp4',
    });

    const wallet = await DurableStore.getWallet(wsId);
    expect(wallet.balance).toBe(10); // 20 initial - 10 settled
    expect(wallet.reservedBalance).toBe(0);
    expect(wallet.lifetimeSpent).toBe(10);

    const ledger = await DurableStore.getLedgerHistory(wsId);
    const eventTypes = ledger.map((l) => l.eventType);
    expect(eventTypes).toContain('GRANT');
    expect(eventTypes).toContain('RESERVE');
    expect(eventTypes).toContain('SETTLE');
  });

  it('6. verifies background reconciliation recovering expired jobs and releasing credits', async () => {
    const wsId = 'ws_smoke_test_recon_05';
    const jobId = '55555555-6666-7777-8888-999999999999';

    await DurableStore.getWallet(wsId);
    // Create job with timestamp > 30 minutes ago
    await DurableStore.saveJob({
      id: jobId,
      workspaceId: wsId,
      userId: 'usr_recon_05',
      clientRequestId: 'req_recon_05',
      styleId: 'NX01',
      styleName: 'Sembang Kawan',
      provider: 'mock',
      durationSeconds: 10,
      requiredCredits: 10,
      status: 'SUBMITTING',
      createdAt: new Date(Date.now() - 35 * 60 * 1000).toISOString(),
      updatedAt: new Date(Date.now() - 35 * 60 * 1000).toISOString(),
    });
    await DurableStore.reserveCredits(wsId, jobId, 10, `res_${jobId}`);

    const walletBefore = await DurableStore.getWallet(wsId);
    expect(walletBefore.reservedBalance).toBe(10);

    // Call reconciliation endpoint with valid CRON_SECRET
    const req = new NextRequest('http://localhost:3000/api/jobs/reconcile', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-cron-secret': TEST_CRON_SECRET,
      },
    });

    const res = await reconcileHandler(req);
    expect(res.status).toBe(200);

    const data = await res.json();
    expect(data.results.released).toBeGreaterThanOrEqual(1);

    // Verify credits released back
    const walletAfter = await DurableStore.getWallet(wsId);
    expect(walletAfter.reservedBalance).toBe(0);
    expect(walletAfter.balance).toBe(20);
  });

  it('7. verifies provider routing safety in mock mode without billing live external APIs', () => {
    const router = new ProviderRouter();
    const adapter = router.resolveProvider(10, 'mock', false);

    expect(adapter.name).toBe('mock');
    expect(adapter.getCapabilities().providerName).toBe('mock');
    expect(adapter.getCapabilities().supportsSpokenBM).toBe(true);
  });

  it('8. executes complete commercial lifecycle: register → login → create order → verify manual payment → grant credits once → generate mock job → retrieve result', async () => {
    process.env.ADMIN_ACCESS_KEY = 'adm_key_live_test_789';
    process.env.USE_MOCK_PROVIDERS = 'true';
    process.env.PUBLIC_CHECKOUT_ENABLED = 'true';

    // Step 1: Register new customer account
    const regReq = new NextRequest('http://localhost:3000/api/auth/register', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'commercial.creator@affimatik.io',
        password: 'PasswordSuper123!',
        fullName: 'Commercial Tester',
        whatsapp: '0123456789',
      }),
    });

    const regRes = await registerHandler(regReq);
    expect(regRes.status).toBe(200);
    const regData = await regRes.json();
    expect(regData.success).toBe(true);
    expect(regData.user.email).toBe('commercial.creator@affimatik.io');
    expect(regData.wallet.balance).toBe(20); // Initial 20 credits provisioned

    // Step 2: Login to acquire valid session cookie
    const loginReq = new NextRequest('http://localhost:3000/api/auth/session', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'commercial.creator@affimatik.io',
        password: 'PasswordSuper123!',
      }),
    });

    const loginRes = await loginHandler(loginReq);
    expect(loginRes.status).toBe(200);
    const loginData = await loginRes.json();
    const cookieHeader = loginRes.headers.get('set-cookie');
    expect(cookieHeader).toBeDefined();
    const sessionCookieMatch = cookieHeader!.match(/affimatik_session=([^;]+)/);
    const sessionCookie = sessionCookieMatch ? sessionCookieMatch[1] : '';
    expect(sessionCookie.length).toBeGreaterThan(10);
    const activeWorkspaceId = loginData.user.workspaceId;

    await DurableStore.setSystemSettings('qr_checkout_config', {
      enabled: true, autoFulfillEnabled: true, instantFullAccessEnabled: true, merchantName: 'AffiMatik Test', bankName: 'Synthetic Bank',
      recipientInfo: 'SIMULATED-STAGING-ONLY', instructions: 'Synthetic test only',
      qrObjectKey: 'system/qr/synthetic.png', qrSha256: 'a'.repeat(64), recipientConfirmed: true,
      provisionalExposureCapMyr: 300, maxAutoOrderMyr: 129,
    });

    // Step 3: Create Order for Starter Plan (RM49, 500 credits) via QR
    const checkoutReq = new NextRequest('http://localhost:3000/api/billing/checkout', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        cookie: `affimatik_session=${sessionCookie}`,
      },
      body: JSON.stringify({
        planId: 'plan_starter',
        paymentMethod: 'qr',
      }),
    });

    const checkoutRes = await checkoutHandler(checkoutReq);
    expect(checkoutRes.status).toBe(200);
    const orderData = await checkoutRes.json();
    expect(orderData.success).toBe(true);
    expect(orderData.orderId).toBeDefined();
    expect(orderData.amountMyr).toBe(49);
    expect(orderData.creditsGranted).toBe(500);
    expect(orderData.qrCheckout.referenceCode).toBeDefined();

    // Verify order is initially PENDING in store
    const initialOrder = await DurableStore.getOrder(orderData.orderId);
    expect(initialOrder?.status).toBe('PENDING');

    const missingReference = await adminOpsHandler(new NextRequest('http://localhost:3000/api/admin/operations', {
      method: 'POST', headers: { 'Content-Type': 'application/json', 'x-admin-key': 'adm_key_live_test_789' },
      body: JSON.stringify({ action: 'manual_verify_payment', orderId: orderData.orderId }),
    }));
    expect(missingReference.status).toBe(400);
    expect((await DurableStore.getOrder(orderData.orderId))?.status).toBe('PENDING');

    const directCommissionPatch = await adminOpsHandler(new NextRequest('http://localhost:3000/api/admin/operations', {
      method: 'POST', headers: { 'Content-Type': 'application/json', 'x-admin-key': 'adm_key_live_test_789' },
      body: JSON.stringify({ action: 'manage_affiliate_commission', commissionId: crypto.randomUUID(), newStatus: 'PAID' }),
    }));
    expect(directCommissionPatch.status).toBe(400);

    // Step 4: Verify manual payment by admin
    const adminVerifyReq = new NextRequest('http://localhost:3000/api/admin/operations', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-key': 'adm_key_live_test_789',
      },
      body: JSON.stringify({
        action: 'manual_verify_payment',
        orderId: orderData.orderId,
        referenceNote: 'MBB_REF_881928301',
      }),
    });

    const verifyRes = await adminOpsHandler(adminVerifyReq);
    expect(verifyRes.status).toBe(200);
    const verifyData = await verifyRes.json();
    expect(verifyData.success).toBe(true);
    expect(verifyData.settlement.status).toBe('PAID');
    // Balance granted once: initial 20 + 100 = 120 credits
    expect(verifyData.settlement.balance).toBe(520);

    // Step 5: Verify double-credit protection (idempotent replay)
    const duplicateAdminVerifyReq = new NextRequest('http://localhost:3000/api/admin/operations', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-admin-key': 'adm_key_live_test_789',
      },
      body: JSON.stringify({
        action: 'manual_verify_payment',
        orderId: orderData.orderId,
        referenceNote: 'MBB_REF_881928301',
      }),
    });

    const duplicateVerifyRes = await adminOpsHandler(duplicateAdminVerifyReq);
    expect(duplicateVerifyRes.status).toBe(200);
    const dupData = await duplicateVerifyRes.json();
    expect(dupData.settlement.balance).toBe(520); // No duplicate grant

    // Step 6: Generate mock video job using acquired customer session
    const clientRequestId = `req_comm_${Date.now()}`;
    const jobReq = new NextRequest('http://localhost:3000/api/jobs', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        cookie: `affimatik_session=${sessionCookie}`,
      },
      body: JSON.stringify({
        styleId: 'NX01',
        clientRequestId,
        imageKeys: ['workspaces/test/inputs/product.png'],
        prompt: 'Ulasan produk kosmetik organik Malaysia',
      }),
    });

    const jobRes = await jobsHandler(jobReq);
    expect(jobRes.status).toBe(200);
    const jobData = await jobRes.json();
    expect(jobData.success).toBe(true);
    expect(jobData.jobId).toBeDefined();
    expect(jobData.reservedCredits).toBe(10);

    // Step 7: Retrieve result with realistic polling (RUNNING -> COMPLETED)
    const getJobReq1 = new NextRequest(`http://localhost:3000/api/jobs?jobId=${jobData.jobId}`, {
      method: 'GET',
      headers: { cookie: `affimatik_session=${sessionCookie}` },
    });
    const poll1Res = await getJobsHandler(getJobReq1);
    expect(poll1Res.status).toBe(200);
    const poll1Data = await poll1Res.json();
    expect(poll1Data.jobId).toBe(jobData.jobId);
    expect(poll1Data.status).toBe('RUNNING');

    // Second poll: provider completes output
    const getJobReq2 = new NextRequest(`http://localhost:3000/api/jobs?jobId=${jobData.jobId}`, {
      method: 'GET',
      headers: { cookie: `affimatik_session=${sessionCookie}` },
    });
    const poll2Res = await getJobsHandler(getJobReq2);
    expect(poll2Res.status).toBe(200);
    const retrievedJob = await poll2Res.json();
    expect(retrievedJob.jobId).toBe(jobData.jobId);
    expect(retrievedJob.status).toBe('COMPLETED');
    expect(retrievedJob.output?.videoUrl).toBeDefined();
    expect(retrievedJob.output?.videoUrl).toContain('.mp4');

    // Step 8: Verify final customer wallet after complete lifecycle
    const finalWallet = await DurableStore.getWallet(activeWorkspaceId);
    // 520 minus 10 settled = 510 remaining available credits
    expect(finalWallet.balance).toBe(510);
    expect(finalWallet.reservedBalance).toBe(0);
    expect(finalWallet.lifetimeGranted).toBe(520);
    expect(finalWallet.lifetimeSpent).toBe(10);
  });

  it('9. verifies public checkout is disabled and returns PAYMENTS_COMING_SOON when PUBLIC_CHECKOUT_ENABLED=false', async () => {
    delete process.env.PUBLIC_CHECKOUT_ENABLED; // Defaults to false

    const loginReq = new NextRequest('http://localhost:3000/api/auth/session', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: 'commercial.creator@affimatik.io',
        password: 'PasswordSuper123!',
      }),
    });
    const loginRes = await loginHandler(loginReq);
    const cookieHeader = loginRes.headers.get('set-cookie');
    const sessionCookieMatch = cookieHeader!.match(/affimatik_session=([^;]+)/);
    const sessionCookie = sessionCookieMatch ? sessionCookieMatch[1] : '';

    const checkoutReq = new NextRequest('http://localhost:3000/api/billing/checkout', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        cookie: `affimatik_session=${sessionCookie}`,
      },
      body: JSON.stringify({
        planId: 'plan_starter',
        paymentMethod: 'manual_fpx',
      }),
    });

    const checkoutRes = await checkoutHandler(checkoutReq);
    expect(checkoutRes.status).toBe(403);
    const data = await checkoutRes.json();
    expect(data.error).toBe('PAYMENTS_COMING_SOON');
    expect(data.message).toContain('Checkout QR belum tersedia');
  });
});
