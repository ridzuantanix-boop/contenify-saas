export function resolveEffectiveAudioMode(spec: StyleDirectorSpec, requested?: 'voiceover' | 'ambient' | 'asmr'): EffectiveAudioMode {
  if (requested === 'ambient' && spec.allowSoundOnly) return 'ambient';
  if (requested === 'asmr' && spec.allowSoundOnly) return 'asmr';
  return spec.defaultAudioMode;
}

export function compileEffectiveAudioDirective(spec: StyleDirectorSpec, effectiveAudioMode: EffectiveAudioMode): string {
  return effectiveAudioMode === 'spoken_presenter'
    ? `Effective audio mode: SPOKEN PRESENTER. ${spec.voiceOrAudio} The visible presenter speaks with accurate lip-sync.`
    : effectiveAudioMode === 'off_camera_voiceover'
      ? `Effective audio mode: OFF-CAMERA VOICEOVER. ${spec.voiceOrAudio} No visible mouth speaks.`
      : effectiveAudioMode === 'ambient'
        ? 'Effective audio mode: AMBIENT. Use only low-level environment sound physically matching the scene. Absolutely no spoken words, voiceover, narration, lip-sync or music.'
        : effectiveAudioMode === 'asmr'
          ? 'Effective audio mode: ASMR. Use only subtle synchronized handling/contact sound produced by visible physical action. Absolutely no spoken words, voiceover, narration, lip-sync or music.'
          : 'Effective audio mode: NO SPEECH. Use no dialogue, voiceover, narration or lip-sync.';
}

export function compileStyleDirector(spec: StyleDirectorSpec, productName: string): string {
  return [
    `[STYLE ${spec.id} — AUTHORITATIVE CREATIVE DIRECTOR]`,
    `Creative concept: ${spec.concept}`,
    `Intended audience experience: ${spec.audienceExperience}`,
    `Opening visual behaviour: ${spec.openingVisual}`,
    `Shot composition: ${spec.shotComposition}`,
    `Scene-selection logic: ${spec.sceneSelection}`,
    `Product interaction: ${spec.productInteraction}`,
    `Presenter visibility: ${spec.presenterVisibility}`,
    `Human acting behaviour: ${spec.humanPerformance}`,
    `Storytelling objective: ${spec.storytellingObjective}`,
    `Relevant product information: ${spec.relevantProductInformation}`,
    `Natural ending: ${spec.naturalEnding}`,
    `Style-specific hard failures: ${spec.hardFailures.join('; ')}.`,
    `Exact product identity reference metadata: "${productName}". The uploaded image guides identity and must not be copied as the first frame.`,
  ].join(' ');
}
